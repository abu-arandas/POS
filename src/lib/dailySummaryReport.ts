import { SaleTransaction, StoreSettings, Shift, CashMovement } from '../types';

export interface DailySummaryData {
  storeName: string;
  currency: string;
  date: string;
  transactions: SaleTransaction[];
  shift?: Shift | null;
  cashMovements?: CashMovement[];
}

export function generateDailySummaryText(data: DailySummaryData): string {
  const { storeName, currency, date, transactions, shift, cashMovements = [] } = data;

  const totalSales = transactions.reduce((s, tx) => s + tx.total, 0);
  const totalTax = transactions.reduce((s, tx) => s + (tx.tax || 0), 0);
  const totalDiscount = transactions.reduce((s, tx) => s + (tx.discount || 0), 0);
  const cashSales = transactions
    .filter((tx) => tx.paymentMethod === 'cash')
    .reduce((s, tx) => s + tx.total, 0);
  const cardSales = transactions
    .filter((tx) => tx.paymentMethod === 'card')
    .reduce((s, tx) => s + tx.total, 0);
  const otherSales = totalSales - cashSales - cardSales;

  // Product popularity
  const productCountMap = new Map<string, number>();
  transactions.forEach((tx) => {
    tx.items.forEach((item) => {
      productCountMap.set(item.productName, (productCountMap.get(item.productName) || 0) + item.quantity);
    });
  });

  const topProducts = Array.from(productCountMap.entries())
    .sort((a, b) => b[1] - a[1])
    .slice(0, 5);

  // Cash movements
  const totalPayIns = cashMovements
    .filter((m) => m.type === 'pay_in')
    .reduce((s, m) => s + m.amount, 0);
  const totalPayOuts = cashMovements
    .filter((m) => m.type === 'pay_out')
    .reduce((s, m) => s + m.amount, 0);

  const openingFloat = shift?.openingFloat || 0;
  const expectedDrawerCash = openingFloat + cashSales + totalPayIns - totalPayOuts;

  const lines = [
    `📊 *${storeName.toUpperCase()} - DAILY REPORT*`,
    `📅 ${date}`,
    ``,
    `💰 *FINANCIAL SUMMARY*`,
    `• Gross Revenue: ${currency}${totalSales.toFixed(2)} (${transactions.length} orders)`,
    `• Cash Collected: ${currency}${cashSales.toFixed(2)}`,
    `• Card / Electronic: ${currency}${cardSales.toFixed(2)}`,
    otherSales > 0 ? `• Other Payments: ${currency}${otherSales.toFixed(2)}` : null,
    `• Tax Collected: ${currency}${totalTax.toFixed(2)}`,
    totalDiscount > 0 ? `• Discounts: ${currency}${totalDiscount.toFixed(2)}` : null,
    ``,
    `💵 *CASH DRAWER AUDIT*`,
    `• Opening Float: ${currency}${openingFloat.toFixed(2)}`,
    totalPayIns > 0 ? `• Cash Deposits (Pay-Ins): +${currency}${totalPayIns.toFixed(2)}` : null,
    totalPayOuts > 0 ? `• Petty Cash Payouts: -${currency}${totalPayOuts.toFixed(2)}` : null,
    `• Expected Cash in Drawer: ${currency}${expectedDrawerCash.toFixed(2)}`,
    shift?.countedCash !== undefined
      ? `• Counted Cash: ${currency}${shift.countedCash.toFixed(2)} (Diff: ${currency}${(shift.countedCash - expectedDrawerCash).toFixed(2)})`
      : null,
    ``,
    topProducts.length > 0 ? `🍔 *TOP SELLING ITEMS*` : null,
    ...topProducts.map(([name, qty], idx) => `${idx + 1}. ${name} (${qty} sold)`),
    ``,
    `Generated by Antigravity POS • ${new Date().toLocaleTimeString()}`,
  ].filter((line): line is string => line !== null);

  return lines.join('\n');
}

export function shareToWhatsApp(text: string, phone?: string): void {
  const cleanPhone = phone ? phone.replace(/[^0-9]/g, '') : '';
  const url = cleanPhone
    ? `https://wa.me/${cleanPhone}?text=${encodeURIComponent(text)}`
    : `https://wa.me/?text=${encodeURIComponent(text)}`;
  window.open(url, '_blank');
}

export function shareViaEmail(subject: string, body: string, email?: string): void {
  const target = email || '';
  const url = `mailto:${target}?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(body)}`;
  window.location.href = url;
}

export async function copyReportToClipboard(text: string): Promise<boolean> {
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch {
    return false;
  }
}
